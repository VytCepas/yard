"""Deterministic AIBOM generation for the governance overlay (ADR-018, #412).

Emits ``.agents/governance/ai-bom.generated.md`` — an AI Bill of Materials the
scaffolder can *derive*: the models CCR is configured to route to (from the
``multi_model`` overlay's ``config.json``, when present), labelled "detected CCR
routes". No LLM (ADR-001); regenerated on every scaffold/upgrade so it never
drifts, exactly like ``capabilities.emit`` (it is "always (over)written").

What the scaffolder *cannot* see — models/APIs a project calls directly (e.g. a
direct Anthropic SDK call) — lives in the user-owned ``ai-declarations.md``,
which is seeded once and preserved. The two files are never mixed: this one is
generated, that one is hand-maintained.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_OUTPUT_REL = Path(".agents/governance/ai-bom.generated.md")
_CCR_CONFIG_REL = Path(".agents/multi-model/config.json")

_GENERATED_HEADER = (
    "<!-- Generated by project-init (ADR-018). Do not edit by hand — this file "
    "is overwritten on every scaffold/upgrade. Hand-declared models/APIs belong "
    "in ai-declarations.md. -->"
)


def extract_ccr_routes(config_path: Path) -> dict[str, list[Any]]:
    """Parse a claude-code-router ``config.json`` into detected routes.

    Returns ``{"routes": [(role, provider, model), ...], "providers": [name]}``.
    Empty (not an error) when the file is absent or unparseable — the
    ``multi_model`` overlay may simply not be installed. The ``Router`` map holds
    ``"provider,model"`` strings keyed by role plus a numeric
    ``longContextThreshold`` that is intentionally skipped (not a route).
    """
    try:
        data = json.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, ValueError):
        return {"routes": [], "providers": []}
    routes: list[tuple[str, str, str]] = []
    router = data.get("Router", {})
    if isinstance(router, dict):
        for role, value in router.items():
            if isinstance(value, str) and "," in value:
                provider, _, model = value.partition(",")
                routes.append((role, provider.strip(), model.strip()))
    providers: list[str] = []
    for prov in data.get("Providers", []) or []:
        if isinstance(prov, dict) and prov.get("name"):
            providers.append(str(prov["name"]))
    return {"routes": routes, "providers": providers}


def render_aibom(detect_root: Path, variables: dict[str, str]) -> str:
    """Build the AIBOM markdown from the recorded selection + emitted overlays.

    *detect_root* is the project root whose live CCR config is inspected. On a
    plain scaffold that is the scaffold target; on upgrade/add/remove it must be
    the real project, NOT the staging render — staging holds the pristine
    template ``config.json``, so detecting there would report template-default
    routes and clobber the user's actual ones on ``--apply``.
    """
    lines: list[str] = [
        _GENERATED_HEADER,
        "",
        "# AI Bill of Materials (AIBOM)",
        "",
        "The AI components this project ships that `project-init` can detect. "
        "Models and APIs called directly (which no config reveals) are recorded "
        "by hand in [`ai-declarations.md`](ai-declarations.md).",
        "",
        "## MCP servers",
        "",
        "_`project-init` ships no MCP servers. Record any you add in "
        "[`ai-declarations.md`](ai-declarations.md)._",
    ]
    lines += ["", "## Detected CCR routes", ""]

    if variables.get("multi_model"):
        ccr = extract_ccr_routes(detect_root / _CCR_CONFIG_REL)
        if ccr["routes"]:
            lines += ["| Role | Provider | Model |", "|---|---|---|"]
            for role, provider, model in ccr["routes"]:
                lines.append(f"| {role} | {provider} | `{model}` |")
            lines += ["", f"_Providers configured: {', '.join(ccr['providers'])}._"]
        else:
            lines.append("_Multi-model overlay present but no routes detected._")
    else:
        lines.append(
            "_Multi-model (CCR) overlay not installed — no routed models to detect. "
            "Record directly-called models in [`ai-declarations.md`](ai-declarations.md)._"
        )
    lines.append("")
    return "\n".join(lines)


def emit(
    target: Path,
    variables: dict[str, str],
    *,
    first_scaffold: bool = True,
    conflicts: list[tuple[Path, Path]] | None = None,
    detect_root: Path | None = None,
) -> list[Path]:
    """Write ``.agents/governance/ai-bom.generated.md``.

    A generated inventory, overwritten on every re-run and upgrade — except that a
    pre-existing user file at this path is preserved as a ``.new`` sibling (never
    clobbered) on the *first* scaffold, or on a later run while an unmerged ``.new``
    sibling from an earlier run is still pending (PI-535).

    *detect_root* — see :func:`render_aibom`; defaults to *target*.
    """
    from project_init.scaffold import _emit_generated

    # Detect CCR routes from the live project (detect_root) so upgrade/remove
    # don't clobber the user's real routes with staging's template default. But
    # on `add multi_model` the live project has no config yet (it's the file
    # being added) — fall back to the freshly-rendered one in *target* (staging)
    # that apply is about to install, so the AIBOM reflects the routes actually
    # being added rather than an empty table.
    root = detect_root or target
    if detect_root is not None and not (detect_root / _CCR_CONFIG_REL).is_file():
        root = target

    return _emit_generated(
        target / _OUTPUT_REL,
        render_aibom(root, variables),
        first_scaffold=first_scaffold,
        conflicts=conflicts,
        rel=_OUTPUT_REL,
    )
